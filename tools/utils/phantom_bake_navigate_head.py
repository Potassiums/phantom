"""
Bake the head of the 3D View's navigation gizmo (Preferences > Viewport > Head) into
``source/blender/editors/space_view3d/view3d_gizmo_navigate_head_data.cc``.

The head is "Head - Planar" from Blender's human base meshes (CC0, by Blender Studio artists,
``datafiles/assets/human_base_meshes``): its Multires at level 4, decimated with X symmetry,
the neck closed, triangulated, centered on its bounding box and scaled to fit a unit sphere.

Run with Phantom (or Blender) in the background::

    phantom -b --factory-startup --python tools/utils/phantom_bake_navigate_head.py -- \
        <human_base_meshes_bundle.blend> <output .cc>
"""

import sys

import bmesh
import bpy
from mathutils import Vector

OBJECT = "Head - Planar"
LEVEL = 4
RATIO = 0.02


def main():
    bundle, output = sys.argv[sys.argv.index("--") + 1:][:2]
    with bpy.data.libraries.load(bundle) as (_src, dst):
        dst.objects = [OBJECT]
    ob = dst.objects[0]
    bpy.context.scene.collection.objects.link(ob)
    ob.modifiers[0].levels = LEVEL
    decimate = ob.modifiers.new("Decimate", 'DECIMATE')
    decimate.ratio = RATIO
    decimate.use_symmetry = True
    decimate.symmetry_axis = 'X'
    mesh = bpy.data.meshes.new_from_object(ob.evaluated_get(bpy.context.evaluated_depsgraph_get()))

    bm = bmesh.new()
    bm.from_mesh(mesh)
    # Close the neck, so the head reads as a solid from below too.
    boundary = [e for e in bm.edges if e.is_boundary]
    bmesh.ops.holes_fill(bm, edges=boundary, sides=0)
    bmesh.ops.triangulate(bm, faces=bm.faces[:])
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces[:])

    lo = Vector([min(v.co[i] for v in bm.verts) for i in range(3)])
    hi = Vector([max(v.co[i] for v in bm.verts) for i in range(3)])
    center = (lo + hi) / 2.0
    radius = max((v.co - center).length for v in bm.verts)
    bm.verts.index_update()

    verts = [tuple(round((v.co[i] - center[i]) / radius * 32767) for i in range(3)) for v in bm.verts]
    tris = [tuple(v.index for v in f.verts) for f in bm.faces]
    assert len(verts) < 65536

    def rows(items, per_line):
        lines = []
        for i in range(0, len(items), per_line):
            lines.append("    " + " ".join("{%d, %d, %d}," % item for item in items[i:i + per_line]))
        return "\n".join(lines)

    with open(output, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(
            "/* SPDX-FileCopyrightText: 2026 Phantom Authors\n"
            " *\n"
            " * SPDX-License-Identifier: GPL-2.0-or-later */\n"
            "\n"
            "/** \\file\n"
            " * \\ingroup spview3d\n"
            " *\n"
            " * The navigation gizmo's head, generated by `tools/utils/phantom_bake_navigate_head.py`\n"
            " * from \"Head - Planar\" of Blender's human base meshes (CC0, by Blender Studio artists).\n"
            " * Facing -Y (the Front view) with +Z up, in a unit sphere (vertices times 1/32767).\n"
            " */\n"
            "\n"
            "#include \"view3d_intern.hh\"\n"
            "\n"
            "namespace blender {\n"
            "\n"
            f"const int view3d_navigate_head_verts_num = {len(verts)};\n"
            f"const int view3d_navigate_head_tris_num = {len(tris)};\n"
            "\n"
            "const short view3d_navigate_head_verts[][3] = {\n"
            f"{rows(verts, 3)}\n"
            "};\n"
            "\n"
            "const unsigned short view3d_navigate_head_tris[][3] = {\n"
            f"{rows(tris, 4)}\n"
            "};\n"
            "\n"
            "}  // namespace blender\n")
    print(f"Baked {len(verts)} vertices, {len(tris)} triangles into {output}")


main()
